`timescale 1ns/1ns

//=============================================================================
// PE 自检测试平台
//=============================================================================
//
// PE 语义(rtl/pe.sv, 同步复位):
//     load=1 : w 装入 w_inner, psum_out 保持
//     load=0 : psum_out <= psum_in + $signed(a) * $signed(w_inner)
//
//------------------------------------------------------------------------------
// 关键点：psum_in 是正常的外部输入，不由本模块的 psum_out 反馈回来
//------------------------------------------------------------------------------
// 测试向量直接给出 psum_in，模拟"上一级 PE 送来的部分和"。期望输出就是
// 代数式本身：
//
//     load=1 -> psum_out == 上一拍的 psum_out   (累加器不动)
//     load=0 -> psum_out == psum_in + a*w       (有符号乘)
//
// 期望值由下面的 e_mac 函数就地算出，不手写常数，避免算错。
// 注意 psum_in / psum_out 都必须是 32 位：psum_in 可以远超 8 位，用窄位宽
// 比较会被静默截断。
//
//------------------------------------------------------------------------------
// 相对原版 pe_tb.sv 的修正
//------------------------------------------------------------------------------
//
// 1) 不再把 psum_out 接回 psum_in。
//    原版 tb 里 psum_in 只由 $fscanf 从文件第 4 列赋值，而那个文件列又被
//    当成"累加结果"填，等于让输入依赖输出；并且它丢掉了 a*w 这一项。
//    本平台让 psum_in 完全由向量提供，与 psum_out 无关。
//    （第 7、8 组用 check_acc 显式做自反馈累加链，但那是**测试意图**，
//      不是隐藏的连接——每一条都写明了 pin 从哪来。）
//
// 2) 复位必须覆盖到第一个 posedge 之后。
//    PE 是同步复位。若 rst 在首个 posedge 之前撤销，复位分支永不执行，
//    psum_out 恒为 x。原版 tb 的 "#5 rst = 1'b0" 早于 t=40 的首个 posedge，
//    正踩此坑。此处 rst 保持到 t=31，覆盖 t=20 的 negedge。
//
// 3) 不使用文件 I/O。
//    本机 iverilog 14.0 (devel) 在 initial 块里做文件 I/O（$fscanf / $fgets
//    / $fdisplay）时，DUT 的时序 always 块会停止正确求值（实测 psum_out 出现
//    555 / 64311 之类与设计不符的值）；去掉文件 I/O 后行为正常。故向量硬编码
//    在下方，结果用 $display 打印。
//
//------------------------------------------------------------------------------
// 相对上一版的改动：ACC_BITS 16 -> 32
//------------------------------------------------------------------------------
//
// 1) tb 的 ACC_BITS 跟随 DUT 改为 32，并且 DUT 例化时**显式传参**。
//    PE 的端口位宽取决于参数，参数不一致时 iverilog 只给 warning，实际行为
//    是输入补零 / 输出截断——静默错。显式传参让 tb 自己决定位宽，不会因为
//    pe.sv 默认值改动而失配。
//
// 2) 打印辅助 s16 -> s32。
//    原来的 s16 会先截成 bit[15:0] 再按 bit[15] 定符号，对 32 位结果会打印
//    出错误的符号；之前所有向量都小于 16 位才没有暴露。同时补打印 0x%08h，
//    32 位的边界值(0x7FFFFFF0 之类)用十进制很难读。
//
// 3) e_mac 改成真正的参考模型：乘积在 8x8 有符号宽度内算完，再符号扩展到
//    ACC_BITS。当前 RTL 是把两个操作数先扩到 ACC_BITS 再相乘（等价于一个
//    32x32 乘法器），对 8 位输入两者数值完全一致；但 tb 不应该照抄 RTL 的
//    内部位宽，否则将来 RTL 把乘法器收窄回 8x8 时，tb 反而会误报失败。
//
// 4) 新增第 7~10 组向量，覆盖 32 位累加器——这是本次改宽累加器的**唯一意义**：
//    原 1~6 组最大只有 60127，16 位累加器也能全过，等于根本没测到 32 位。
//      7) 正向累加链 127*127 连加 5 次 -> 80645，跨越 16 位有符号上限 32767
//         与无符号上限 65535
//      8) 负向累加链 -> -80645，跨越 -32768 与 -65535
//      9) 32 位高位与符号位：0x7FFFFFF0+1、0x80000000+1、0xFFFFFFF0+2
//     10) 极值操作数 w=-128、a=-128：127*(-128) 与 (-128)*(-128)
//
//------------------------------------------------------------------------------
// 波形
//------------------------------------------------------------------------------
//   vvp sim_pe 生成 pe.vcd，用 gtkwave 打开：
//       gtkwave pe.vcd
//   关注: pe_tb.rst / load / a / w / psum_in / u_pe.w_inner / u_pe.psum_out
//   psum_in / psum_out 现在是 32 位，看波形时按有符号十进制显示更方便。
//=============================================================================

module pe_tb;

    localparam A_BITS   = 8;
    localparam W_BITS   = 8;
    localparam ACC_BITS = 32;

    reg                  clk;
    reg                  rst;
    reg                  load;
    reg  [A_BITS-1:0]    a;
    reg  [W_BITS-1:0]    w;
    reg  [ACC_BITS-1:0]  psum_in;      // 由测试向量提供的外部输入
    wire [ACC_BITS-1:0]  psum_out;

    reg  [W_BITS-1:0]    w_reg;        // 当前已装载的权重
    reg  [ACC_BITS-1:0]  prev_out;     // 上一拍的 psum_out, load 拍的期望值
    integer err_cnt;
    integer vec_cnt;

    //------------------------------------------------------------------------
    // 时钟：40ns 周期。t=20 首个 negedge，t=40 首个 posedge
    //------------------------------------------------------------------------
    initial clk = 1'b0;
    always #20 clk = ~clk;

    //------------------------------------------------------------------------
    // 复位：保持到 t=31（覆盖 t=20 的 negedge，早于 t=40 的 posedge）
    //------------------------------------------------------------------------
    initial begin
        rst = 1'b1;
        #31 rst = 1'b0;
    end

    //------------------------------------------------------------------------
    // DUT（显式传参：位宽由 tb 决定，不依赖 pe.sv 的默认值）
    //------------------------------------------------------------------------
    PE #(
        .A_BITS   (A_BITS),
        .W_BITS   (W_BITS),
        .ACC_BITS (ACC_BITS)
    ) u_pe (
        .clk      (clk),
        .rst      (rst),
        .load     (load),
        .a        (a),
        .w        (w),
        .psum_in  (psum_in),
        .psum_out (psum_out)
    );

    //------------------------------------------------------------------------
    // 有符号打印辅助
    //------------------------------------------------------------------------
    // 32 位值用 %d 直接打印会按无符号显示，负数会变成 4294967288 这种大数。
    // 先转成 $signed 再交给 %0d，就会打印成 -8。
    // integer 是 32 位有符号，正好容纳 ACC_BITS=32。
    function integer s32(input [31:0] v);   s32  = $signed(v);  endfunction
    function integer s8 (input [7:0]  v);   s8   = $signed(v);  endfunction

    //------------------------------------------------------------------------
    // 期望值：直接由语义算出（参考模型，位宽独立于 RTL 内部实现）
    //------------------------------------------------------------------------
    // load=1: RTL 走 "w_inner <= w" 分支，psum_out **保持不动**，
    //         既不等于当拍 psum_in，也不做乘累加。
    // load=0: psum_out = psum_in + $signed(a) * $signed(w_inner)
    //
    // 实测确认(见 posedge 探针):
    //     [P t=100] load=1 psum_in=1000 psum_out=0    <- 保持旧值
    //     [P t=140] load=0 a=7 psum_in=0   psum_out(次拍)=21
    function [ACC_BITS-1:0] e_mac(
        input [ACC_BITS-1:0] p,
        input [A_BITS-1:0]   aa,
        input [W_BITS-1:0]   ww
    );
        reg signed [A_BITS-1:0]        a_s;
        reg signed [W_BITS-1:0]        w_s;
        reg signed [A_BITS+W_BITS-1:0] prod;   // 8x8 -> 16 位有符号积
        reg signed [ACC_BITS-1:0]      p_s;
        reg signed [ACC_BITS-1:0]      sum;
        begin
            a_s  = $signed(aa);
            w_s  = $signed(ww);
            prod = a_s * w_s;      // 乘积宽度 = prod 的声明宽度 16
            p_s  = $signed(p);
            sum  = p_s + prod;     // prod 自动符号扩展到 ACC_BITS
            e_mac = sum;
        end
    endfunction


    //------------------------------------------------------------------------
    // 激励 + 记分板
    //------------------------------------------------------------------------
    // check(load, a, w, psum_in)
    //   negedge 施加向量（让输入在下一个 posedge 前稳定建立）
    //   -> 等 posedge 让 PE 真正采样到本拍的值
    //   -> 等 negedge 读结果并与代数期望值比较。
    //
    //   注意必须先在 negedge 落定再等 posedge：如果在 posedge 之后才赋值，
    //   PE 采到的仍是上一拍的输入，结果会整体滞后一拍，而滞后的结果恰好能
    //   和"用本拍输入算出的期望值"对上，制造出假的通过。
    task automatic check(
        input                l,
        input [A_BITS-1:0]   aa,
        input [W_BITS-1:0]   ww,
        input [ACC_BITS-1:0] pin
    );
        reg [ACC_BITS-1:0] exp;
        begin
            @(negedge clk) ;              // 对齐到 negedge 边界

            load    = l;
            a       = aa;
            w       = ww;
            psum_in = pin;

            @(posedge clk) ;              // PE 采样本向量的 load/a/w/psum_in
            @(negedge clk) ;              // 结果稳定后读取

            if (l) exp = prev_out;                       // 保持不动
            else   exp = e_mac(pin, aa, w_reg);          // psum_in + a*w

            vec_cnt = vec_cnt + 1;
            if (psum_out !== exp) begin
                err_cnt = err_cnt + 1;
                $display("  FAIL #%0d  load=%0d a=%0d w=%0d psum_in=%0d(0x%08h)  psum_out=%0d(0x%08h)  expected=%0d(0x%08h)",
                         vec_cnt, l, s8(aa), s8(ww), s32(pin), pin, s32(psum_out), psum_out, s32(exp), exp);
            end else begin
                $display("  pass #%0d  load=%0d a=%0d w=%0d psum_in=%0d(0x%08h)  psum_out=%0d(0x%08h)",
                         vec_cnt, l, s8(aa), s8(ww), s32(pin), pin, s32(psum_out), psum_out);
            end

            if (l) w_reg = ww;            // 跟踪装载后的权重, 供下一拍算期望
            prev_out = psum_out;          // load 拍要拿它当期望
        end
    endtask

    //------------------------------------------------------------------------
    // 累加链：psum_in 取上一拍的**真实**输出
    //------------------------------------------------------------------------
    // 这是阵列里 psum_out -> psum_in 自反馈的最小复现。用它才能验证"累加器
    // 真的在累加"，而不是每条向量都从外部灌一个独立的部分和。
    //
    // 级联效应：某一条 FAIL 后 prev_out 会记成 DUT 的**实际**输出，链上后续
    // 向量用的就不再是"正确历史"，因此后面的结果不可信——可能继续 FAIL，也
    // 可能因为两边同时被污染而意外对上（实测把 DUT 压成 16 位时，#22 FAIL 后
    // #23 反而 pass）。判断链式段落时只看**第一条** FAIL。
    task automatic check_acc(
        input [A_BITS-1:0] aa
    );
        begin
            check(1'b0, aa, {W_BITS{1'b0}}, prev_out);
        end
    endtask

    initial begin
        load    = 1'b0;
        a       = 0;
        w       = 0;
        psum_in = 0;
        w_reg    = 0;
        prev_out = 0;
        err_cnt = 0;
        vec_cnt = 0;

        // 波形输出，供 gtkwave 查看
        $dumpfile("pe.vcd");
        $dumpvars(0, pe_tb);

        // 等复位撤销，让 psum_out 稳定为 0
        wait (~rst);
        @(negedge clk) ;

        $display("--------------------------------------------------");
        $display(" PE self-check  (A_BITS=%0d W_BITS=%0d ACC_BITS=%0d)",
                 A_BITS, W_BITS, ACC_BITS);
        $display("--------------------------------------------------");

        //------------------------------------------------------------------
        // 1) 装载路径 (w=+3)
        //    load=1 时 PE 走 "w_inner <= w" 分支，psum_out 保持不动，
        //    既不等于当拍 psum_in，也不做乘累加。
        //------------------------------------------------------------------
        check(1'b1, 8'd0,   8'd3,   32'd0);       // 装载 w=+3, 输出保持 0
        check(1'b1, 8'd0,   8'd3,   32'd1000);    // 装载拍, 输出仍保持 0 (非 1000)

        //------------------------------------------------------------------
        // 2) 基本 MAC: psum_in + a*w
        //------------------------------------------------------------------
        check(1'b0, 8'd7,   8'd0,   32'd0);       // 0 + 7*3 = 21
        check(1'b0, 8'd10,  8'd0,   32'd100);     // 100 + 30 = 130
        check(1'b0, 8'd0,   8'd0,   32'd1000);    // 1000 + 0 = 1000

        //------------------------------------------------------------------
        // 3) 负权重 w=-4 (8'hFC=252)
        //    这一组是符号乘法的关键覆盖: 负积必须被正确加到 psum_in 上
        //------------------------------------------------------------------
        check(1'b1, 8'd0,   8'd252, 32'd7);       // 装载 w=-4, 输出保持 1000
        check(1'b0, 8'd2,   8'd0,   32'd51);      // 51  + 2*(-4) = 43
        check(1'b0, 8'd5,   8'd0,   32'd100);     // 100 + 5*(-4) = 80

        //------------------------------------------------------------------
        // 4) 负乘数 a=-3 (8'hFD=253): 负 * 负 = 正
        //------------------------------------------------------------------
        check(1'b0, 8'd253, 8'd0,   32'd43);      // 43 + (-3)*(-4) = 55

        //------------------------------------------------------------------
        // 5) w=0: 乘积为 0, 输出等于 psum_in
        //------------------------------------------------------------------
        check(1'b1, 8'd0,   8'd0,   32'd55);      // 装载 w=0, 输出保持 55
        check(1'b0, 8'd100, 8'd0,   32'd1234);    // 1234 + 0 = 1234

        //------------------------------------------------------------------
        // 6) 大 psum_in 与 a=-1 (8'hFF=255)
        //------------------------------------------------------------------
        check(1'b1, 8'd0,   8'd1,   32'd55);      // 装载 w=+1, 输出保持 1234
        check(1'b0, 8'd127, 8'd0,   32'd60000);   // 60000 + 127 = 60127
        check(1'b0, 8'd255, 8'd0,   32'd1000);    // 1000 + (-1)*1 = 999

        //------------------------------------------------------------------
        // 7) 32 位累加链 (正向): w=+127, a=+127, 每步 +16129
        //    这是本次改宽累加器的核心覆盖 —— 16 位累加器在最后三步必错
        //------------------------------------------------------------------
        check(1'b1, 8'd0,   8'd127, 32'd0);       // 装载 w=+127, 输出保持 999
        check(1'b0, 8'd127, 8'd0,   32'd0);       // 0     + 127*127 = 16129
        check_acc  (8'd127);                      // 16129 + 16129 = 32258
        check_acc  (8'd127);                      // 32258 + 16129 = 48387  > 32767
        check_acc  (8'd127);                      // 48387 + 16129 = 64516  < 65535
        check_acc  (8'd127);                      // 64516 + 16129 = 80645  > 65535

        //------------------------------------------------------------------
        // 8) 32 位累加链 (负向): w=-127 (8'h81=129), a=+127, 每步 -16129
        //------------------------------------------------------------------
        check(1'b1, 8'd0,   8'd129, 32'd0);       // 装载 w=-127, 输出保持 80645
        check(1'b0, 8'd127, 8'd0,   32'd0);       // 0      - 16129 = -16129
        check_acc  (8'd127);                      // -16129 - 16129 = -32258
        check_acc  (8'd127);                      // -32258 - 16129 = -48387  < -32768
        check_acc  (8'd127);                      // -48387 - 16129 = -64516
        check_acc  (8'd127);                      // -64516 - 16129 = -80645  < -65535

        //------------------------------------------------------------------
        // 9) 32 位高位与符号位
        //    0x7FFFFFF0 这类值在 16 位累加器里会被截断成 0xFFF0, 必错
        //------------------------------------------------------------------
        check(1'b1, 8'd0,   8'd1,   32'd0);            // 装载 w=+1, 输出保持 -80645
        check(1'b0, 8'd1,   8'd0,   32'h7FFF_FFF0);    // 0x7FFFFFF0 + 1 = 0x7FFFFFF1
        check(1'b0, 8'd1,   8'd0,   32'h8000_0000);    // 0x80000000 + 1 = 0x80000001
        check(1'b0, 8'd2,   8'd0,   32'hFFFF_FFF0);    // -16 + 2*1      = -14
        check(1'b0, 8'd255, 8'd0,   32'sd1_000_000);   // 1000000 + (-1)*1 = 999999

        //------------------------------------------------------------------
        // 10) 极值操作数: w=-128 (8'h80), a=-128 / a=+127
        //------------------------------------------------------------------
        check(1'b1, 8'd0,    8'h80, 32'd0);       // 装载 w=-128, 输出保持 999999
        check(1'b0, 8'h7F,   8'd0,  32'd0);       // 0 + 127*(-128)  = -16256
        check(1'b0, 8'h80,   8'd0,  32'd0);       // 0 + (-128)*(-128) = +16384

        $display("--------------------------------------------------");
        $display("  vectors : %0d", vec_cnt);
        $display("  errors  : %0d", err_cnt);
        if (err_cnt == 0) $display("  Simulation pass");
        else              $display("  Mismatch detected");
        $display("--------------------------------------------------");
        $finish;
    end

endmodule
